#!/usr/bin/env python3
"""Write THIRD-PARTY-NOTICES.md: every crate Vergence's programs are built from
that is not Vergence's own, with its license expression and the text of its
license and notice files.

Our own script, as decided on 2026-11-08 (no borrowed license tool): it asks
Cargo (`cargo metadata`) for the dependency graph, keeps what the programs
link (normal dependencies, followed from the workspace members; not
dev-dependencies, which only tests use, and not build-dependencies, which
run at build time only), for the platforms we build for (Linux and FreeBSD,
x86_64), and reads each crate's LICENSE*, COPYING*, NOTICE* and UNLICENSE
files from where Cargo keeps its source. Apache-2.0 asks that a NOTICE file
travel with redistributions (section 4d), so those are reproduced whole.

Run from the checkout on a machine with Rust (Control has none):
    python3 tools/notices.py            # writes THIRD-PARTY-NOTICES.md
    python3 tools/notices.py --check    # exit 1 if the file is out of date
"""

import json
import os
import subprocess
import sys

PLATFORMS = ["x86_64-unknown-linux-gnu", "x86_64-unknown-freebsd"]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")
OUT = "THIRD-PARTY-NOTICES.md"

# Code copied into our own crates rather than depended on. Cargo cannot see
# these; each keeps its license file beside it.
VENDORED = [
    ("Smithay's smallvil example", "crates/vergence-server/LICENSE-smithay.txt",
     "crates/vergence-server started from it on 2026-11-07 (per-file attribution in the source)."),
    ("SCOWL (Spell Checker Oriented Word Lists), the spelling list", "data/words/SCOWL-COPYRIGHT.txt",
     "data/words/en_US.txt is made from SCOWL 2020.12.07 by tools/make-words.py (editor milestone 1); data, not code."),
    ("Inter, the interface font (SIL Open Font License 1.1)", "data/fonts/Inter-OFL.txt",
     "data/fonts/InterVariable.ttf and InterVariable-Italic.ttf, Inter 4.1 from rsms/inter's release, unchanged; installed in share/vergence/fonts."),
    ("JetBrains Mono, the monospace font (SIL Open Font License 1.1)", "data/fonts/JetBrainsMono-OFL.txt",
     "data/fonts/JetBrainsMono-Variable.ttf and JetBrainsMono-Variable-Italic.ttf, JetBrains Mono 2.304's variable fonts from JetBrains/JetBrainsMono's release, unchanged but for the file names; installed in share/vergence/fonts."),
    ("Liberation Sans, Serif and Mono, the PDF reader's stand-ins for Helvetica, Times and Courier (SIL Open Font License 1.1)", "data/fonts/Liberation-OFL.txt",
     "data/fonts/Liberation{Sans,Serif,Mono}-{Regular,Bold,Italic,BoldItalic}.ttf, Liberation 2.1.5 from liberationfonts/liberation-fonts's release (liberation-fonts-ttf-2.1.5.tar.gz), unchanged; installed in share/vergence/fonts."),
]


def metadata():
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked"]
    for p in PLATFORMS:
        cmd += ["--filter-platform", p]
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def shipped(meta):
    """Package ids reachable from the workspace members through normal dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), list(meta["workspace_members"])
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return seen - set(meta["workspace_members"])


def license_files(manifest_path):
    d = os.path.dirname(manifest_path)
    found = []
    for name in sorted(os.listdir(d)):
        p = os.path.join(d, name)
        if os.path.isfile(p) and name.lower().startswith(LICENSE_PREFIXES):
            with open(p, encoding="utf-8", errors="replace") as f:
                found.append((name, f.read().strip()))
    return found


def render(meta):
    pkgs = {p["id"]: p for p in meta["packages"]}
    ids = sorted(shipped(meta), key=lambda i: (pkgs[i]["name"], pkgs[i]["version"]))
    out = [
        "# Third-party notices",
        "",
        "Vergence is licensed under Apache-2.0 OR GPL-2.0-or-later (LICENSE-APACHE,",
        "LICENSE-GPL). Its programs are built with the code listed here, each under its",
        "own license, reproduced below. Generated by `tools/notices.py` from `cargo",
        "metadata` (" + ", ".join(PLATFORMS) + "); do not edit by hand.",
        "",
        "## Summary",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    for i in ids:
        p = pkgs[i]
        out.append(f"| {p['name']} | {p['version']} | {p.get('license') or '(see files)'} |")
    out += ["", "## Code copied into Vergence", ""]
    for what, path, note in VENDORED:
        with open(path, encoding="utf-8") as f:
            text = f.read().strip()
        out += [f"### {what}", "", note, "", "```", text, "```", ""]
    out += ["## License and notice texts", "",
            "Each distinct text is printed once; later crates with the same text point back to it.", ""]
    first = {}      # normalized text -> where it was printed
    for i in ids:
        p = pkgs[i]
        out += [f"### {p['name']} {p['version']}", "",
                f"License: {p.get('license') or '(see files)'}"]
        if p.get("repository"):
            out.append(f"Source: {p['repository']}")
        out.append("")
        files = license_files(p["manifest_path"])
        if not files:
            out += ["(No license file in the crate; its license expression is above.)", ""]
        for name, text in files:
            key = " ".join(text.split())
            if key in first:
                out += [f"`{name}`: the same text as {first[key]}, above.", ""]
            else:
                first[key] = f"{p['name']} {p['version']}'s `{name}`"
                out += [f"`{name}`:", "", "```", text, "```", ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    text = render(metadata())
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print(f"{OUT} is out of date: run python3 tools/notices.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
